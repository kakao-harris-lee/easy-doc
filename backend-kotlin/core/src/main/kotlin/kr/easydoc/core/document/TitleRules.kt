package kr.easydoc.core.document

import kr.easydoc.core.text.stripControlChars

// 문서 제목을 정하는 규칙.
//
// ## 제목은 **본문에서도 파일 이름에서도 만들지 않는다** (2026-08-20 사용자 재판정)
//
// 제목의 바탕은 **사용자가 제목 칸에 적어 준 값 하나뿐**이다. 없으면 [FALLBACK_TITLE] 이다.
// 두 갈래가 차례로 닫혔고, 닫힌 사유가 서로 다르므로 둘 다 적어 둔다 — 다음 사람이 "왜
// 파라미터를 열었다 닫았나"를 묻는다.
//
// ### ⑴ 본문 유도 갈래 — 게이트 27 Critical ① (2026-08-20 1차)
//
// 이전 판은 제목이 없으면 **본문 첫 줄**을 30자로 잘라 제목으로 썼다(원본
// `app/services/documents.py::_resolve_title`·`_shorten_derived_title` 포팅). 그 갈래는
// 방어 둘을 동시에 우회한다.
//
// - `documents.title` 은 **평문 컬럼**이다. 원문은 AEAD 로 봉하는데 그 조각이 옆 칸에
//   평문으로 남는다 — DB·백업·덤프·향후 검색 표면 전부에 걸린다.
// - 업로드 시점에는 **마스킹이 돌지 않는다**(마스킹 선행 불변식의 대상은 LLM 전송이고
//   그것은 워커의 일이다). 그래서 첫 줄에 주민등록번호가 있으면 그대로 평문 저장된다.
//
// ### ⑵ 파일 이름 갈래 — 열었다가 **되돌렸다** (2026-08-20 2차 재판정)
//
// ⑴ 을 고칠 때 그 자리를 파일 이름으로 메웠다. 근거는 "본문은 사용자가 맡긴 내용이고 파일
// 이름은 사용자가 스스로 붙여 건넨 이름"이라는 구분이었다. **그 구분은 규정을 이기지
// 못한다** — 다음 둘이 파일 이름 사용을 이미 금지하고 있었다.
//
// - 계약 `contracts/easy-doc-v1.yaml` `DocumentTextRequest.title` —
//   *"파일명은 제목으로 쓰지 않는다 — 파일명 자체가 개인정보일 수 있다."*
// - `migration-safety-gate` I-4 (차단 등급) — *"파일명은 아예 저장하지 않는다."*
//
// 실제 위험도 같은 종류였다. `홍길동_주민등록등본.docx` 는 이름만으로 **누가 어떤 서류를
// 올렸는지**를 평문으로 남긴다. 경로·확장자·제어문자를 떼도 남는 것은 그 부분이다.
//
// 그래서 파일 이름은 **유스케이스 밖으로 나가지 않는다**: 형식 판별에만 쓰이고 버려진다
// (`DocumentTextExtractor` KDoc). 이 함수는 파일 이름을 받을 **자리 자체가 없다.**
//
// ## 이 규칙을 실행으로 되짚는 자리
//
// 여기는 순수 규칙이라 "호출자가 무엇을 넘겼는가"를 잴 수 없다. 그 축은 실 DB 에서
// `JdbcDocumentStoreTest` 의 두 탐지기가 진다 — 본문 표식·파일 이름 표식이 `documents` 행의
// **어느 평문 열에도** 남지 않는다(열 목록은 `information_schema` 에서 파생한다).

/** 제목을 정할 근거가 하나도 없을 때 쓰는 이름. */
const val FALLBACK_TITLE: String = "제목 없음"

/**
 * 제목을 정한다. **사용자가 제목 칸에 적어 준 값만** 쓴다.
 *
 * 본문도 파일 이름도 쓰지 않는다 — 사유는 이 파일 머리말의 ⑴·⑵ 다. 적어 준 것이 없거나
 * 다듬고 나서 남는 것이 없으면 [FALLBACK_TITLE] 이다.
 *
 * ## 다듬는 규칙
 *
 * 앞뒤 공백을 털고, 제어문자를 걷어내고, [MAX_TITLE_LENGTH] 에서 **자른다(거절하지
 * 않는다)**. 상한 초과를 거절하지 않는 것은 계약이 정한 것이다
 * (`x-input-limits.max_title_length`) — 목록에 보일 이름일 뿐이라 업로드를 통째로
 * 실패시킬 이유가 없다.
 *
 * 제어문자를 자르기 **전에** 걷어낸다. 순서를 뒤집으면 잘린 길이가 보이는 글자 수와
 * 어긋나고, 남은 제어문자가 내보내기(XML) 시점에 터진다.
 *
 * @param given 사용자가 적어 준 제목. 없거나 공백·제어문자뿐이면 [FALLBACK_TITLE] 이다.
 */
fun resolveTitle(given: String?): String = sanitizeName(given.orEmpty().trim()) ?: FALLBACK_TITLE

/**
 * 이름을 저장할 수 있는 모양으로 다듬는다. 남는 것이 없으면 `null`.
 *
 * 앞뒤 공백은 **한 번 더** 턴다 — 제어문자를 지우면 가려져 있던 공백이 드러난다
 * (`"\u0000 안내"` → `" 안내"`).
 */
private fun sanitizeName(raw: String): String? =
    takeCodePoints(stripControlChars(raw), MAX_TITLE_LENGTH).trim().ifEmpty { null }
