package kr.easydoc.core.text

/**
 * XML 1.0 이 허용하지 않는 제어문자. 탭(`\x09`)·개행(`\x0A`)·복귀(`\x0D`)는 문서 구조를
 * 이루므로 남긴다.
 *
 * 원본: `app/text.py::_CONTROL_CHARS`.
 */
private val CONTROL_CHARS = Regex("[\\x00-\\x08\\x0B\\x0C\\x0E-\\x1F\\x7F]")

/**
 * XML 에 담을 수 없는 제어문자를 제거한다 (탭·개행·복귀는 유지).
 *
 * 원본: `app/text.py::strip_control_chars`.
 *
 * ## 왜 필요한가
 *
 * docx 를 이루는 XML 은 탭·개행·복귀를 뺀 제어문자를 담을 수 없다. 그런 문자가 섞인
 * 채 저장되면 내보내기 시점에 XML 직렬화가 실패하고, 사용자는 원인을 알 수 없는 500 을
 * 받는다. 입력 단계에서 걸러 두면 그 실패가 사용자에게 도달하지 않는다.
 *
 * ## 지우고 다른 문자로 바꾸지 않는 이유
 *
 * 이 문자들은 사람이 읽는 내용이 아니라 편집기·변환기가 흘린 흔적이라, 자리를 남기면
 * 본문에 정체불명의 공백만 늘어난다.
 *
 * ## 마스킹과 역할이 겹치지 않는다
 *
 * `kr.easydoc.core.privacy` 의 마스킹도 보이지 않는 문자를 다루지만 **지우지 않는다** —
 * 탐색용 뷰에서만 걷어내고 잘라내는 것은 언제나 원문이다. 마스킹 앞단에서 입력을
 * 정규화해 버리면 자리표시자를 되돌렸을 때 원문이 복원되지 않는다. 두 처리의 순서를
 * 바꾸거나 하나로 합치지 않는다.
 */
fun stripControlChars(text: String): String = CONTROL_CHARS.replace(text, "")
