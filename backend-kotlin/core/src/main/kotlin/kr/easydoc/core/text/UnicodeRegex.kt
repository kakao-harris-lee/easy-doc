package kr.easydoc.core.text

import java.util.regex.Pattern

/**
 * 유니코드를 인식하는 문자 클래스로 정규식을 컴파일한다.
 *
 * ## 기본값을 쓰지 않는 이유
 *
 * Java 정규식의 `\d`·`\s`·`\w` 는 **기본적으로 ASCII 전용**이다. `\d` 는 `[0-9]` 만
 * 잡고, `\s` 는 NBSP(U+00A0)를 공백으로 보지 않는다. 우리가 다루는 입력은 공공기관
 * 문서에서 뽑은 한국어 텍스트이고, hwpx·pdf 추출본에는 전각 숫자(`１２３`)와 NBSP 가
 * 실제로 섞여 들어온다.
 *
 * 이 차이가 실제로 문제가 되는 자리는 둘이다.
 *
 * 1. **마스킹** — 자릿수 경계를 지키는 `(?<!\d)`·`(?!\d)` 가 ASCII 전용이면 전각 숫자가
 *    앞뒤에 붙은 숫자열을 "독립된 13자리"로 오판해 **과잉 마스킹**한다. 반대 방향으로,
 *    `\d` 로 적은 **숫자 자리**는 이 플래그 덕분에 전각·아라비아-인도 표기까지 잡는다
 *    (parity fixture `masking-card-unicode-digit-fullwidth`·`masking-rrn-unicode-digit-head`).
 * 2. **문장 분리** — NBSP 로 이어진 문장이 하나로 붙어 길이 검사를 우회한다.
 *
 * ## 이 플래그가 덮는 것은 **축약 클래스뿐이다** (교차 리뷰 X-2 · privacy-gate 판정 §1)
 *
 * 이전 판 KDoc 은 "주민등록번호가 전각 숫자로 적혀 있으면 ASCII `\d` 는 통째로 놓친다"고
 * 적어, 이 플래그를 켜면 전각 주민등록번호가 잡히는 것처럼 읽혔다. 그 뒤 판은 그것을
 * 성별코드 `[1-8]` 하나의 문제로 좁혀 적었는데, 그것도 **절반이었다.**
 *
 * 이 플래그가 바꾸는 것은 **축약 클래스(`\d`·`\s`·`\w`)와 POSIX 클래스뿐**이다.
 * 패턴에 손으로 적은 리터럴 — 숫자 범위든 구분자든 — 은 그대로 ASCII 로 남는다.
 * privacy-gate 실측이 그 빈자리를 두 종류로 갈랐다.
 *
 * - **종류 A(ASCII 숫자 범위)**: RRN 성별코드가 `[1-8]` 이라 전각 성별코드에서 매치가
 *   끊겼다. 카드번호에는 이 종류가 **없다** — 숫자 자리가 전부 `\d` 다.
 * - **종류 B(ASCII 구분자 리터럴)**: RRN 의 `[ \t]`·`-` 와 CARD 의 `[- ]`. **두 패턴
 *   모두**에 있었고, 전각 하이픈(U+FF0D)·마이너스(U+2212)·엔 대시(U+2013)·NBSP(U+00A0)·
 *   전각 공백(U+3000)이 전부 통과했다. 즉 **카드번호도 뚫려 있었다** — 전각 숫자는
 *   잡히지만 전각 하이픈으로 이어진 카드번호는 잡히지 않았다.
 *
 * 둘 다 `Masking.kt` 에서 고쳤다. **고친 자리는 이 파일이 아니라 패턴 쪽이다** —
 * 이 플래그로 해결되는 문제가 아니었다는 것이 요점이다.
 *
 * ## 종류 B 를 "집합 열거"로 고친 것도 절반이었다 (privacy-gate 판정 §4-ter.2)
 *
 * 구분자를 문자 집합으로 넓힌 1차 수정은 **누락은 닫았지만 과잉을 열었다.** 집합만 열거하고
 * **반복 상한을 지정하지 않아** `공백* 하이픈? 공백*` 이 표 열 맞춤(공백 여러 칸)까지 삼켰고,
 * 서로 다른 값인 접수번호 6자리와 관리번호 7자리가 하나의 주민등록번호로 결합됐다.
 * 반대로 카드번호는 구분자가 **한 문자**뿐이라 `1234 - 5678 - …` 을 놓쳤다.
 *
 * 지금은 `Masking.kt` 의 `SEP` 하나가 둘을 함께 정한다 — `(?: SPACE? HYPHEN SPACE? | SPACE? )`,
 * 최대 3문자. **판정 기준이 문자 종류가 아니라 개수**라는 것이 요점이다: 같은 자리에 공백이
 * 둘 이상이면 그것은 구분이 아니라 정렬이다.
 *
 * ## 이 파일의 교훈
 *
 * 세 번의 정정이 전부 같은 형태였다 — **"이 장치가 덮는 범위"를 실제보다 넓게 적었다.**
 * 이 플래그가 덮는 것은 축약 클래스뿐이고, 문자 집합 열거가 덮는 것은 종류뿐이며,
 * 반복 상한은 또 다른 축이다. 새 문자를 집합에 더할 때마다 **그것이 몇 개까지 허용되는지**를
 * 함께 정하지 않으면 같은 자리가 다시 열린다.
 *
 * 즉 이것은 "Python 과 같은 값을 내려고" 맞춘 것이 아니라, 한국어 문서를 다루는
 * 요구사항이 유니코드 인식을 요구하기 때문이다. Python `re` 가 str 패턴에서 같은
 * 규칙을 쓰는 것은 같은 이유에서다.
 *
 * `\uXXXX` 같은 명시적 코드포인트 표기와 `[가-힣]` 같은 범위 표기는 이 플래그의
 * 영향을 받지 않는다 — 플래그가 바꾸는 것은 축약 클래스와 POSIX 클래스뿐이다.
 */
internal fun unicodeRegex(pattern: String): Regex = Pattern.compile(pattern, Pattern.UNICODE_CHARACTER_CLASS).toRegex()
