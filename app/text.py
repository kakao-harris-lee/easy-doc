"""텍스트 정규화 — 저장 경로와 렌더 경로가 함께 쓰는 최소 규칙.

XML(docx)은 탭·개행·복귀를 뺀 제어문자를 담을 수 없다. 그런 문자가 섞인 채 저장되면
내보내기에서 lxml이 ValueError를 던지고, 사용자는 원인을 알 수 없는 500을 받는다
(그 500은 CORS 미들웨어 바깥에서 만들어져 브라우저가 상태 코드조차 읽지 못한다).

지금 정규화가 걸린 자리는 두 곳이고, 역할이 서로 다르다.

1. **저장 시점** — 문서 제목(`_resolve_title`)과 검수 수정본(`save_review`). 사용자가
   직접 준 값이라 입력 검증과 함께 그 자리에서 다듬는 것이 자연스럽고, 저장된 값이
   그대로 화면에 다시 나가기 때문이다.
2. **렌더 진입부** — `render_export`. 산출물 본문을 이루는 나머지 재료(워커가 저장한
   AI 초안 `easy_text`, 복원해 넣는 마스킹 원문)는 **어느 저장 경로에서도 정규화되지
   않는다**. 그 둘에 대해서는 여기가 방어의 전부이지 "이중 방어"가 아니다.

초안·마스킹 원문까지 저장 시점에 정규화하지 않는 이유: 초안은 LLM 응답이고 마스킹
원문은 원문에서 잘라낸 조각이라, 저장 전에 손대면 원문 대조(검수 화면)와 수정률 KPI의
기준값이 우리가 고친 판본으로 바뀐다. 내보낼 때만 다듬는 편이 기록을 건드리지 않는다.
"""

import re

#: XML 1.0이 허용하지 않는 제어문자. 탭(\x09)·개행(\x0a)·복귀(\x0d)는 문서 구조를
#: 이루므로 남긴다.
_CONTROL_CHARS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def strip_control_chars(text: str) -> str:
    """XML에 담을 수 없는 제어문자를 제거한다 (탭·개행·복귀는 유지).

    지우고 다른 문자로 바꾸지 않는 이유: 이 문자들은 사람이 읽는 내용이 아니라 편집기·
    변환기가 흘린 흔적이라, 자리를 남기면 본문에 정체불명의 공백만 늘어난다.
    """
    return _CONTROL_CHARS.sub("", text)
